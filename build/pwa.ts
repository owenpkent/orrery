import type { Plugin } from 'vite';

/**
 * Small, dependency-free PWA support for a static site served under a subpath:
 *  - emits sw.js with the built JS and CSS precached (cache name changes every build)
 *  - adds <link rel="preload"> for the critical latin fonts, which Vite does not discover from CSS
 */
export function pwa(): Plugin {
  let base = '/';
  return {
    name: 'orrery-pwa',
    apply: 'build',
    configResolved(c) {
      base = c.base;
    },
    transformIndexHtml: {
      order: 'post',
      handler(html, ctx) {
        const files = Object.keys(ctx.bundle ?? {});
        const critical = [
          /^assets\/instrument-serif-latin-400-normal-.*\.woff2$/,
          /^assets\/instrument-serif-latin-400-italic-.*\.woff2$/,
          /^assets\/inter-latin-wght-normal-.*\.woff2$/,
        ];
        const tags = files
          .filter((f) => critical.some((re) => re.test(f)))
          .map(
            (f) =>
              `    <link rel="preload" href="${base}${f}" as="font" type="font/woff2" crossorigin />`,
          )
          .join('\n');
        return tags ? html.replace('</head>', `${tags}\n  </head>`) : html;
      },
    },
    generateBundle(_, bundle) {
      const precache = [base, ...Object.keys(bundle).filter((f) => /\.(js|css)$/.test(f))]
        .map((f) => (f === base ? f : base + f))
        .concat(`${base}manifest.webmanifest`, `${base}icons/icon-192.png`);
      const version = Object.keys(bundle)
        .filter((f) => /\.(js|css)$/.test(f))
        .sort()
        .join('|');
      let hash = 0;
      for (const ch of version) hash = (hash * 31 + ch.charCodeAt(0)) | 0;
      const source = `// Generated by build/pwa.ts. Offline cache for the static site.
const CACHE = 'orrery-${(hash >>> 0).toString(36)}';
const PRECACHE = ${JSON.stringify(precache)};
const SCOPE = self.registration.scope;

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches
      .open(CACHE)
      .then((c) => Promise.all(PRECACHE.map((u) => c.add(u).catch(() => undefined))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || !req.url.startsWith(SCOPE)) return;
  const url = new URL(req.url);
  // Pages: network first so a new deploy shows up, cached copy when offline.
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(SCOPE, copy));
          return res;
        })
        .catch(() => caches.match(SCOPE).then((r) => r || Response.error())),
    );
    return;
  }
  // Hashed assets never change: cache first. Everything else in scope: stale while revalidate.
  const immutable = url.pathname.includes('/assets/');
  e.respondWith(
    caches.match(req).then((hit) => {
      if (hit && immutable) return hit;
      const net = fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => hit || Response.error());
      return hit || net;
    }),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}
